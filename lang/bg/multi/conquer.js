/* Meivi games · several phones · text of the game "conquer" · Bulgarian
   The map itself (shapes, names of regions, municipalities and villages) is in conquer-map.js: another country has its own.
   points: what a place is worth, by its kind (c capital, r regional town, m municipality, v village). */
MEIVI.mtext("conquer", {
  time: "10–40 мин",
  about: "Всеки тайно посяга към едно място на картата. Взимаш го само ако никой друг не е поискал същото.",
  rules: [
    "На картата са столицата, 27-те области, общините им и по едно село във всяка община.",
    "Всеки рунд всеки тайно избира едно свободно място.",
    "Ако си единственият, който го е избрал, то става твое. Ако двама или повече посегнат към едно и също място, никой не го взима и то остава свободно.",
    "Точки: столицата 10, областен град 5, община 3, село 1.",
    "В началото са отворени само столицата и областните градове. Щом един областен град бъде взет, общините в областта му се отварят за всички. Щом една община бъде взета, отваря се и селото ѝ.",
    "Домакинът избира 15, 30 или 50 рунда. Печели който събере най-много точки.",
    "Хитрината: всички искат София. Затова понякога малката община е по-сигурната плячка."
  ],
  points: { c: 10, r: 5, m: 3, v: 1 },
  map: () => (MEIVI.mdata || {}).conquer,
  t: {
    pick: "Какво завладяваш?",
    result: "Какво стана",
    nothing: "не избра нищо",
    took: (place, n) => `взе ${place} (+${n})`,
    clash: place => `сблъсък за ${place}`,
    /* a place in a sentence: "взе община Троян" */
    place: (k, n) => k === "c" ? `столицата ${n}` : k === "r" ? n : k === "m" ? `община ${n}` : `с. ${n}`,
    holds: o => [
      o.c ? "столицата" : "",
      o.r ? (o.r === 1 ? "1 област" : `${o.r} области`) : "",
      o.m ? (o.m === 1 ? "1 община" : `${o.m} общини`) : "",
      o.v ? (o.v === 1 ? "1 село" : `${o.v} села`) : ""
    ].filter(Boolean).join(", "),
    noLand: "без земи",
    ruler: "Владетел на България",
    lands: "Кой какво владее",
    /* the words on and around the map */
    map: {
      back: "← България",
      hint: "Докосни място на картата.",
      hintIn: "Докосни община на картата или в списъка.",
      enter: n => `Влез в ${n}`,
      choose: "Избирам",
      yours: place => `Твоят избор: ${place}`,
      kind: { c: "столица", r: "областен град", area: "област", m: "община", v: "село" },
      pts: n => `${n} т.`,
      region: (n, area) => area ? n : `Област ${n}`,
      town: n => `гр. ${n}`,
      village: n => `с. ${n}`,
      inMun: n => `общ. ${n}`,
      free: o => "Свободни сега: " + ([
        o.c ? "столицата" : "",
        o.r ? (o.r === 1 ? "1 областен град" : `${o.r} областни града`) : "",
        o.m ? (o.m === 1 ? "1 община" : `${o.m} общини`) : "",
        o.v ? (o.v === 1 ? "1 село" : `${o.v} села`) : ""
      ].filter(Boolean).join(", ") || "няма"),
      openHint: "Числото в областта показва колко свободни места има вътре."
    }
  }
});
